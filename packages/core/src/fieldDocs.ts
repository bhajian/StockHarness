// Built-in meanings and units for every field StockHarness syncs or writes (#84, #394). Agents read these through
// the Schema Catalog. FIELD_DOCS holds names that mean the same everywhere; COLLECTION_FIELD_DOCS holds the
// meaning a name has in one collection (`date`, `name`, `value`, cash-flow changes vs balance-sheet levels, the
// simulation ledgers). Curated docs (edited, or oh.describe) and a transform's declared output fields win over
// both. A unit test (tests/unit/field-docs.test.ts) fails when a live field has no doc.
export type FieldDoc = { description: string; unit?: string };

const RC = 'reportedCurrency';
const RC_SHARE = 'reportedCurrency/share';
const FRACTION = 'fraction (0.25 = 25%)';
const MULTIPLE = 'ratio (×)';
const PP = 'percent points';
const cur = (description: string): FieldDoc => ({ description, unit: RC });
const usd = (description: string): FieldDoc => ({ description, unit: 'USD' });
const frac = (description: string): FieldDoc => ({ description, unit: FRACTION });
const times = (description: string): FieldDoc => ({ description, unit: MULTIPLE });
const perShare = (description: string): FieldDoc => ({ description, unit: RC_SHARE });
const days = (description: string): FieldDoc => ({ description, unit: 'days' });
const count = (description: string): FieldDoc => ({ description, unit: 'count' });
const text = (description: string): FieldDoc => ({ description });
/** Growth vs the previous period (quarter over quarter for quarterly rows, year over year for FY rows). */
const growth = (what: string): FieldDoc =>
  frac(
    `Growth of ${what} vs the previous period (quarter over quarter on quarterly rows, year over year on FY rows).`,
  );
/** Cumulative growth per share over N years, as FMP computes it. */
const nYearGrowth = (n: string, what: string): FieldDoc =>
  frac(`Cumulative ${n}-year growth of ${what} per share, as computed by FMP (2.0 = +200%).`);
/** A ratio on the row's period, as FMP computes it (quarterly rows use the quarter's flows, not TTM). */
const onPeriod =
  'Computed by FMP on the row’s period (a quarter on quarterly rows, not trailing twelve months).';

