/** The built-in doc of a field: the collection’s own meaning first, then the shared dictionary. */
export function builtinFieldDoc(collection: string | undefined, name: string): FieldDoc | undefined {
  const own = collection ? COLLECTION_FIELD_DOCS[collection]?.[name] : undefined;
  if (own?.description) return own;
  const shared = FIELD_DOCS[name];
  return shared?.description ? shared : undefined;
}
